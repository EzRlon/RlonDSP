import json
import shutil
import sys
from pathlib import Path


def read_pkg(node_modules: Path, name: str):
    pkg = node_modules / name / "package.json"
    if not pkg.exists():
        return {}
    try:
        return json.loads(pkg.read_text(encoding="utf-8"))
    except Exception:
        return {}


def main():
    node_modules = Path(sys.argv[1])
    roots = sys.argv[2:]
    keep = set()

    def add(name):
        if name in keep:
            return
        keep.add(name)
        pkg = read_pkg(node_modules, name)
        deps = pkg.get("dependencies", {})
        for dep in deps:
            add(dep)

    for root in roots:
        add(root)

    for child in node_modules.iterdir():
        if child.name.startswith("@") and child.is_dir():
            for scoped in child.iterdir():
                full_name = f"{child.name}/{scoped.name}"
                if full_name not in keep:
                    shutil.rmtree(scoped, ignore_errors=True)
                else:
                    print("keep", full_name)
            if not any(child.iterdir()):
                child.rmdir()
        elif child.name not in keep:
            shutil.rmtree(child, ignore_errors=True)
        else:
            print("keep", child.name)


if __name__ == "__main__":
    main()
